#!/usr/bin/env node
/* Writes js/react-kit-data.js from the NorthStar React kit so the docs show real React code:
   - usage snippets: every "@example <component-id>" ... "@end" region in dashboards/app/src/kit/examples.tsx
     (that file typechecks with the app, so a snippet on the site always compiles)
   - the kit API: every exported function in src/kit/ui.tsx with its props type, as written in the source

     node tools/react-kit-export.mjs          write js/react-kit-data.js
     node tools/react-kit-export.mjs --check  exit 1 if js/react-kit-data.js is out of date */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const KIT = join(ROOT, "dashboards/app/src/kit");
/* every kit source file except the examples, in a stable order */
const ui = readdirSync(KIT).filter((f) => f.endsWith(".tsx") && f !== "examples.tsx").sort().map((f) => readFileSync(join(KIT, f), "utf8")).join("\n");
const ex = readFileSync(join(KIT, "examples.tsx"), "utf8");

/* API: export function Name<...>({ ... }: { props }) */
const api = [];
for (const m of ui.matchAll(/\/\*([^*]*(?:\*(?!\/)[^*]*)*)\*\/\s*\n?(?:export type [^\n]*\n)?|export function (\w+)(<[^>]*>)?\(\{[^}]*\}\s*:\s*\{([\s\S]*?)\}\)\s*\{/g)) {
  if (!m[2]) continue;
  const props = m[4].replace(/\s+/g, " ").trim();
  /* the comment on the line(s) directly above the export, if any; section banners are skipped */
  const lines = ui.slice(0, m.index).replace(/\n$/, "").split("\n");
  let note = "", i = lines.length - 1;
  if (/\*\/\s*$/.test(lines[i] || "")) { const buf = []; while (i >= 0) { buf.unshift(lines[i]); if (/\/\*/.test(lines[i])) break; i--; } note = buf.join(" ").replace(/\/\*|\*\//g, "").replace(/\s+/g, " ").trim(); }
  if (/^-{3,}/.test(note)) note = "";
  api.push({ name: m[2], generic: m[3] || "", props: props.split(/;\s*/).map((p) => p.trim()).filter(Boolean), note });
}
const exportsSet = new Set([...api.map((a) => a.name), "toast", "Toaster", "CommandDialog", "Col"]);

/* Examples */
const examples = {};
for (const m of ex.matchAll(/^([ \t]*)\/\/ @example ([\w-]+)\n([\s\S]*?)^[ \t]*\/\/ @end/gm)) {
  const lines = m[3].replace(/\s+$/, "").split("\n");
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  const code = lines.map((l) => l.slice(indent)).join("\n");
  const uses = [...new Set([...code.matchAll(/\b([A-Z]\w+|toast)\b/g)].map((x) => x[1]).filter((n) => exportsSet.has(n)))];
  examples[m[2]] = { code, uses };
}

const out = `/* Generated by tools/react-kit-export.mjs from dashboards/app/src/kit. Do not edit by hand. */
(function () {
  window.NS = window.NS || {};
  window.NS.REACT_KIT = ${JSON.stringify({ source: "dashboards/app/src/kit", api, examples }, null, 1)};
})();
`;
const file = join(ROOT, "js/react-kit-data.js");
if (process.argv.includes("--check")) {
  const same = existsSync(file) && readFileSync(file, "utf8") === out;
  console.log(same ? "react kit export: up to date" : "react kit export: out of date. Run node tools/react-kit-export.mjs");
  process.exit(same ? 0 : 1);
}
writeFileSync(file, out);
console.log(`react kit export: ${api.length} components, ${Object.keys(examples).length} examples -> js/react-kit-data.js`);
